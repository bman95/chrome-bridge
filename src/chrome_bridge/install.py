"""Per-profile native-messaging host registration (Windows).

Each Chrome profile scripted by chrome-bridge gets its own native-messaging
host name (``com.chromebridge.bridge.<profile>``), manifest file, and launcher
batch file with that profile's port baked in — see docs/multi-profile.md for
why one shared host name cannot work. This module generates those files and
writes the HKCU registry key Chrome reads to find the manifest.

Registry writes go through :mod:`winreg` directly (not by shelling out to
``reg.exe``) so they can be mocked in tests. The native host launcher itself
must be a real Windows-executable ``.bat`` — Chrome spawns it directly — so
that one piece stays a generated file, not a Python function call.
"""

from __future__ import annotations

import sys
from pathlib import Path

from .bridge import HOST_NAME_PREFIX

REGISTRY_KEY_ROOT = r"Software\Google\Chrome\NativeMessagingHosts"

_LAUNCHER_TEMPLATE = """@echo off
REM Native Messaging host launcher for {host_name} (profile "{profile}").
REM Generated by `chrome-bridge init` — do not edit by hand, re-run init instead.
REM Chrome spawns this with the manifest path (and, on Windows, the calling
REM extension origin) as arguments; %* forwards them to the Python host, which
REM ignores them. stdin/stdout MUST stay binary, so nothing here may print to
REM stdout — diagnostics go to stderr (1>&2) so they never corrupt the NM pipe.
REM
REM cd to this script's own directory so `uv run` resolves the project's
REM virtualenv regardless of Chrome's working directory.
cd /d "%~dp0"
set CBR_BRIDGE_PORT={port}
where uv >nul 2>nul
if errorlevel 1 (
  echo run_nmh_{profile}.bat: 'uv' not found on PATH; install uv or add it to PATH 1>&2
  exit /b 1
)
uv run python -m chrome_bridge.bridge.nmh %*
"""


def host_name(profile: str) -> str:
    return f"{HOST_NAME_PREFIX}.{profile}"


def launcher_path(project_root: Path, profile: str) -> Path:
    return project_root / f"run_nmh_{profile}.bat"


def manifest_path(project_root: Path, profile: str) -> Path:
    return project_root / f"nmh-manifest.{profile}.local.json"


def write_launcher(project_root: Path, profile: str, port: int) -> Path:
    """Write the profile's launcher .bat with its port baked in.

    Written with CRLF line endings: cmd.exe can mis-parse a lone-LF batch file
    (a `setlocal`/label line can split mid-token) — see .gitattributes.
    """
    path = launcher_path(project_root, profile)
    content = _LAUNCHER_TEMPLATE.format(
        host_name=host_name(profile), profile=profile, port=port
    )
    path.write_bytes(content.replace("\n", "\r\n").encode("utf-8"))
    return path


def write_manifest(
    project_root: Path, profile: str, *, extension_ids: list[str]
) -> Path:
    """Write the profile's native-messaging manifest, pointing at its launcher.

    ``allowed_origins`` is always written as a list (even for one id): Chrome
    may assign the same or different extension ids per profile depending on
    platform behaviour we haven't verified yet (see docs/multi-profile.md), so
    treating it as a growable array from day one avoids a format migration.
    """
    import json

    path = manifest_path(project_root, profile)
    payload = {
        "name": host_name(profile),
        "description": f"Chrome Bridge Native Messaging host for profile {profile}",
        "path": str(launcher_path(project_root, profile)),
        "type": "stdio",
        "allowed_origins": [f"chrome-extension://{eid}/" for eid in extension_ids],
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def register_native_host(profile: str, manifest_file: Path) -> None:
    """Write the HKCU registry key pointing Chrome at ``manifest_file``.

    Windows-only. Raises :class:`RuntimeError` off Windows since there is no
    registry to write to (Linux/macOS use a manifest directory instead, not
    yet implemented here).
    """
    if sys.platform != "win32":
        raise RuntimeError(
            "native host registration is only implemented for Windows "
            "(HKCU NativeMessagingHosts registry key)"
        )
    import winreg

    key_path = f"{REGISTRY_KEY_ROOT}\\{host_name(profile)}"
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, key_path) as key:
        winreg.SetValueEx(key, "", 0, winreg.REG_SZ, str(manifest_file))


def unregister_native_host(profile: str) -> None:
    """Delete the HKCU registry key for ``profile``'s native host, if present."""
    if sys.platform != "win32":
        raise RuntimeError("native host registration is only implemented for Windows")
    import winreg

    key_path = f"{REGISTRY_KEY_ROOT}\\{host_name(profile)}"
    try:
        winreg.DeleteKey(winreg.HKEY_CURRENT_USER, key_path)
    except FileNotFoundError:
        pass


def patch_allowed_origins(manifest_file: Path, extension_id: str) -> None:
    """Append ``extension_id`` to an existing manifest's allowed_origins, if absent."""
    import json

    data = json.loads(manifest_file.read_text(encoding="utf-8"))
    origin = f"chrome-extension://{extension_id}/"
    origins = data.setdefault("allowed_origins", [])
    if origin not in origins:
        origins.append(origin)
    manifest_file.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
